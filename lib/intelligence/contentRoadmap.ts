/** Compact counts for tooling / docs generation. */
export function summarizeContentRoadmap(): {
  total: number;
  byEra: Record<RoadmapEraId, number>;
  byCategory: Record<string, number>;
  byPriority: Record<RoadmapPriority, number>;
  byImportance: Record<ContentGapImportance, number>;
} {
  const byEra = {
    "early-internet": 0,
    "web-2": 0,
    "social-media": 0,
    "tiktok-modern": 0,
  } satisfies Record<RoadmapEraId, number>;
  const byCategory: Record<string, number> = {};
  const byPriority = { 1: 0, 2: 0, 3: 0 } satisfies Record<
    RoadmapPriority,
    number
  >;
  const byImportance = {
    high: 0,
    medium: 0,
    low: 0,
  } satisfies Record<ContentGapImportance, number>;

  for (const row of CONTENT_EXPANSION_ROADMAP) {
    byEra[row.roadmapEra] += 1;
    byCategory[row.category] = (byCategory[row.category] ?? 0) + 1;
    byPriority[row.priority] += 1;
    byImportance[row.importance] += 1;
  }

  return {
    total: CONTENT_EXPANSION_ROADMAP.length,
    byEra,
    byCategory,
    byPriority,
    byImportance,
  };
}