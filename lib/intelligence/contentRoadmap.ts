import type { CulturalEra } from "@/types";
import type { CulturalClusterId } from "./clusters";
import type {
  ContentGapCategory,
  ContentGapEntry,
  ContentGapImportance,
  RoadmapEraId,
  RoadmapPriority,
} from "./contentGapTypes";

export type { RoadmapEraId, RoadmapPriority } from "./contentGapTypes";

export const ROADMAP_ERA_META: Record<
  RoadmapEraId,
  { label: string; years: string; culturalEras: CulturalEra[] }
> = {
  "early-internet": {
    label: "Early internet",
    years: "1990s–2005",
    culturalEras: ["pre-internet", "early-web"],
  },
  "web-2": {
    label: "Web 2.0",
    years: "2005–2015",
    culturalEras: ["web-2"],
  },
  "social-media": {
    label: "Social media era",
    years: "2015–2020",
    culturalEras: ["social"],
  },
  "tiktok-modern": {
    label: "TikTok / modern era",
    years: "2020–present",
    culturalEras: ["short-form", "gen-alpha"],
  },
};

export interface RoadmapEntry extends ContentGapEntry {
  roadmapEra: RoadmapEraId;
  /** Suggested build priority (1 = highest urgency). */
  priority: RoadmapPriority;
}

type RoadmapSeed = {
  id: string;
  name: string;
  suggestedSlug: string;
  category: ContentGapCategory;
  importance: ContentGapImportance;
  priority: RoadmapPriority;
  roadmapEra: RoadmapEraId;
  reason: string;
  relatedTopics: string[];
  clusters?: CulturalClusterId[];
  status?: ContentGapEntry["status"];
  satisfiedBy?: string[];
  matchHints?: string[];
  notes?: string;
};

function eraFor(roadmapEra: RoadmapEraId): CulturalEra | CulturalEra[] {
  const eras = ROADMAP_ERA_META[roadmapEra].culturalEras;
  return eras.length === 1 ? eras[0]! : eras;
}

function seed(row: RoadmapSeed): RoadmapEntry {
  return {
    id: row.id,
    name: row.name,
    suggestedSlug: row.suggestedSlug,
    category: row.category,
    importance: row.importance,
    priority: row.priority,
    roadmapEra: row.roadmapEra,
    culturalEra: eraFor(row.roadmapEra),
    relatedTopics: row.relatedTopics,
    clusters: row.clusters,
    status: row.status ?? "planned",
    reason: row.reason,
    satisfiedBy: row.satisfiedBy ?? [],
    matchHints: row.matchHints ?? [row.name.toLowerCase()],
    notes: row.notes,
  };
}

